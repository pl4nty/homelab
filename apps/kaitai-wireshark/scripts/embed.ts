// Writes src/lua-sources.generated.ts (git-ignored) from the Kaitai Struct Lua runtime at a pinned commit and
// src/lua/glue.lua, so the generator imports the Lua sources without a bundler loader or file system access.
import { readFileSync, writeFileSync } from 'node:fs';

// renovate: datasource=git-refs depName=https://github.com/kaitai-io/kaitai_struct_lua_runtime branch=master
const RUNTIME_COMMIT = '81e3c385afb9a80edea85bbbbd85008d3f9fa155';
const FILES = ['class', 'enum', 'kaitaistruct', 'string_decode', 'string_stream', 'utils'];

async function get(file: string): Promise<string> {
  const url = `https://raw.githubusercontent.com/kaitai-io/kaitai_struct_lua_runtime/${RUNTIME_COMMIT}/${file}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

const runtime = Object.fromEntries(await Promise.all(FILES.map(async (f) => [f, await get(`${f}.lua`)])));
const license = await get('LICENSE');
const glue = readFileSync(new URL('../src/lua/glue.lua', import.meta.url), 'utf8');

writeFileSync(
  new URL('../src/lua-sources.generated.ts', import.meta.url),
  `// Generated by scripts/embed.ts. Do not edit.

export const RUNTIME_LICENSE = ${JSON.stringify(`-- Includes the Kaitai Struct Lua runtime (${RUNTIME_COMMIT}):\n${license.trimEnd().replace(/^/gm, '-- ')}`)};

export const RUNTIME: Record<string, string> = ${JSON.stringify(runtime, null, 2)};

export const GLUE = ${JSON.stringify(glue)};
`,
);
