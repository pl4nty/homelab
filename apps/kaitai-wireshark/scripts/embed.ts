// Writes src/lua-sources.generated.ts from src/lua/, so the generator imports the Lua sources without a bundler
// loader or file system access. `--check` fails if the file is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/lua/', import.meta.url);
const out = new URL('../src/lua-sources.generated.ts', import.meta.url);

const runtime: Record<string, string> = {};
for (const f of readdirSync(new URL('runtime/', dir)).sort()) {
  if (f.endsWith('.lua')) runtime[f.slice(0, -4)] = readFileSync(new URL(`runtime/${f}`, dir), 'utf8');
}
const glue = readFileSync(new URL('glue.lua', dir), 'utf8');

const text = `// Generated by scripts/embed.ts from src/lua/. Do not edit.
// The Kaitai Struct Lua runtime (src/lua/runtime) is MIT licensed, see src/lua/runtime/LICENSE.

export const RUNTIME: Record<string, string> = ${JSON.stringify(runtime, null, 2)};

export const GLUE = ${JSON.stringify(glue)};
`;

if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== text) {
    console.error('src/lua-sources.generated.ts is stale: run npm run embed');
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
