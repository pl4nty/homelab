// Writes src/lua-sources.generated.ts from src/lua/, so the generator imports the Lua sources without a bundler
// loader or file system access. `--check` fails if the file is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const read = (path: string) => readFileSync(new URL(`../src/${path}`, import.meta.url), 'utf8');
const runtime = readdirSync(new URL('../src/lua/runtime/', import.meta.url))
  .filter((f) => f.endsWith('.lua'))
  .sort()
  .map((f) => [f.slice(0, -4), read(`lua/runtime/${f}`)]);

const text = `// Generated by scripts/embed.ts from src/lua/. Do not edit.
// The Kaitai Struct Lua runtime (src/lua/runtime) is MIT licensed, see src/lua/runtime/LICENSE.

export const RUNTIME: Record<string, string> = ${JSON.stringify(Object.fromEntries(runtime), null, 2)};

export const GLUE = ${JSON.stringify(read('lua/glue.lua'))};
`;

if (!process.argv.includes('--check')) {
  writeFileSync(new URL('../src/lua-sources.generated.ts', import.meta.url), text);
} else if (read('lua-sources.generated.ts') !== text) {
  console.error('src/lua-sources.generated.ts is stale: run npm run embed');
  process.exit(1);
}
